/**
 * Immutable archives produced by Python's standard ZIP writer from hand-authored format records.
 *
 * These bytes are deliberately not regenerated by [BackupArchiveWriter]. The encrypted constants
 * are deterministic, frozen envelope-v1 wrappers around those independent ZIP bytes.
 */
class BackupGoldenArchiveCompatibilityTest {
    @Test
    fun independentlyWrittenV1ArchivePreservesDocumentAndAssets() {
        assertV1Archive(decodeGolden(GOLDEN_V1_BASE64))
    }

    @Test
    fun independentlyWrittenV2ArchivePreservesRawAndCorrectedOcrRelations() {
        assertV2Archive(decodeGolden(GOLDEN_V2_BASE64))
    }

    @Test
    fun immutableEncryptedV1ArchiveDecryptsAndVerifies() {
        val encrypted = decodeGolden(GOLDEN_ENCRYPTED_V1_BASE64)
        assertEquals(GOLDEN_ENCRYPTED_V1_SHA256, sha256(encrypted))

        assertV1Archive(decryptGolden(encrypted))
    }

    @Test
    fun immutableEncryptedV2ArchiveDecryptsAndVerifies() {
        val encrypted = decodeGolden(GOLDEN_ENCRYPTED_V2_BASE64)
        assertEquals(GOLDEN_ENCRYPTED_V2_SHA256, sha256(encrypted))

        assertV2Archive(decryptGolden(encrypted))
    }

    @Test
    fun immutableEncryptedGoldenRejectsWrongPasswordCorruptionAndTruncation() {
        val encrypted = decodeGolden(GOLDEN_ENCRYPTED_V2_BASE64)

        assertEnvelopeFailure(EnvelopeFailure.AUTHENTICATION_FAILED) {
            decryptGolden(encrypted, "wrong golden password")
        }
        assertEnvelopeFailure(EnvelopeFailure.AUTHENTICATION_FAILED) {
            decryptGolden(encrypted.copyOf().apply { this[80] = (this[80].toInt() xor 1).toByte() })
        }
        assertEnvelopeFailure(EnvelopeFailure.TRUNCATED) {
            decryptGolden(encrypted.copyOf(encrypted.size - 1))
        }
    }

    private fun assertV1Archive(archive: ByteArray) {
        val staging = MemoryStagingSink()
        assertEquals(GOLDEN_V1_SHA256, sha256(archive))

        val verified = readAndVerify(archive, staging)

        assertEquals(RME_BACKUP_FORMAT_VERSION_V1, verified.manifest.formatVersion)
        assertNull(verified.ocr)
        assertEquals("Golden folder", verified.folders.single().name)
        assertEquals("Golden document", verified.documents.single().title)
        assertEquals("Legacy OCR text", verified.pages.single().ocrText)
        assertEquals(GOLDEN_PAGE_SHA256, sha256(staging.assets.getValue(GOLDEN_PAGE_PATH).toByteArray()))
        assertEquals(GOLDEN_SOURCE_SHA256, sha256(staging.assets.getValue(GOLDEN_SOURCE_PATH).toByteArray()))
    }

    private fun assertV2Archive(archive: ByteArray) {
        val staging = MemoryStagingSink()
        assertEquals(GOLDEN_V2_SHA256, sha256(archive))

        val verified = readAndVerify(archive, staging)
        val ocr = requireNotNull(verified.ocr)

        assertEquals(RME_BACKUP_FORMAT_VERSION_V2, verified.manifest.formatVersion)
        assertNotNull(verified.ocr)
        assertEquals("Raw OCR 日本語", verified.pages.single().ocrText)
        assertEquals("Raw OCR 日本語", ocr.artifacts.single().rawText)
        assertEquals("Corrected OCR 日本語", ocr.corrections.single().correctedText)
        assertEquals("Corrected OCR 日本語", ocr.corrections.single().lineCorrections.single().correctedText)
        assertEquals("Raw OCR 日本語", ocr.lines.records().single().rawText)
        assertEquals(GOLDEN_PAGE_SHA256, sha256(staging.assets.getValue(GOLDEN_PAGE_PATH).toByteArray()))
        assertEquals(GOLDEN_SOURCE_SHA256, sha256(staging.assets.getValue(GOLDEN_SOURCE_PATH).toByteArray()))
    }

    private fun decryptGolden(
        encrypted: ByteArray,
        password: String = GOLDEN_PASSWORD,
    ): ByteArray {
        val output = ByteArrayOutputStream()
        EncryptedBackupEnvelope.decrypt(
            encryptedSource = ByteArrayInputStream(encrypted),
            plaintextZipDestination = output,
            password = password.toCharArray(),
        )
        return output.toByteArray()
    }

    private fun assertEnvelopeFailure(expected: EnvelopeFailure, block: () -> Unit) {
        val failure = assertThrows(BackupEnvelopeException::class.java, block)
        assertEquals(expected, failure.failure)
    }
}

private fun decodeGolden(encoded: String): ByteArray =
    Base64.getMimeDecoder().decode(encoded.trimIndent())

